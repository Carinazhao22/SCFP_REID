            if self.neck_feat == 'after':
                return torch.cat(
                    [feat, local_feat_1_bn / 3, local_feat_2_bn / 3, local_feat_3_bn / 3], dim=1)
            else:
                return torch.cat(
                    [global_feat, local_feat_1 / 3, local_feat_2 / 3, local_feat_3 / 3], dim=1)

